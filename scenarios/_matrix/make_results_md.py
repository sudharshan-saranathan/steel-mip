#!/usr/bin/env python3
"""Emit docs/RESULTS_TABLES.md -- every aggregate table, as markdown.

For feeding results to tools that read prose (NotebookLM, LLM context) rather
than data. Those tools cannot aggregate a 46,656-row table; handing them raw
rows invites invented numbers. This emits the aggregates already computed, in
a format they can quote correctly.

Regenerate rather than hand-edit:  python3 scenarios/_matrix/make_results_md.py
"""

import pathlib
import sys

import pandas as pd

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import axes as AX  # noqa: E402

ROOT = HERE.parents[1]
OUT = ROOT / "docs" / "RESULTS_TABLES.md"

COORDS = ["ccoal", "ng", "h2_start", "scrap_rate", "grid_ef_target",
          "ramp", "build_cap", "legacy", "avg_emi"]
LEVERS = [c for c in COORDS if c != "avg_emi"]

df = pd.read_parquet(HERE / "results" / "matrix.parquet")
df["ok"] = df.solve_result == "solved"
sol = df[df.ok]
cal = sol[sol.extrapolated == 0]

buf = []
w = buf.append


def table(frame, index_name=None, float_fmt="{:.3f}"):
    """DataFrame -> markdown table."""
    f = frame.copy()
    if index_name:
        f.index.name = index_name
    cols = [str(c) for c in f.columns]
    w("| " + " | ".join([f.index.name or ""] + cols) + " |")
    w("|" + "---|" * (len(cols) + 1))
    for idx, row in f.iterrows():
        cells = [float_fmt.format(v) if isinstance(v, float) else str(v)
                 for v in row]
        w(f"| {idx} | " + " | ".join(cells) + " |")
    w("")


def paired(frame, lever, lo, hi, metric="lcop", by=None):
    keys = [c for c in COORDS if c != lever]
    a = frame[frame[lever] == lo].set_index(keys)[metric]
    b = frame[frame[lever] == hi].set_index(keys)[metric]
    a, b = a[~a.index.duplicated()], b[~b.index.duplicated()]
    j = pd.concat({"lo": a, "hi": b}, axis=1).dropna()
    d = j.hi - j.lo
    if by is None:
        return d.mean(), len(d)
    g = j.assign(d=d).groupby(by, observed=True)
    return g.agg(delta=("d", "mean"), n_pairs=("d", "size"))


w("# Results tables — India steel decarbonisation design matrix")
w("")
w("Machine-generated by `scenarios/_matrix/make_results_md.py` from")
w("`matrix.parquet`. Do not hand-edit; regenerate.")
w("")
w("**Reading conventions.** Feasibility figures use all 46,656 scenarios.")
w("Cost figures ($/t crude steel) use only the calibrated subset — the")
w("scenarios whose 2050 grid emission factor lies in 350–550 gCO2/kWh, where")
w("the coupled electricity tariff is inside its calibration anchors. All")
w("differences are *paired*: computed over scenarios feasible at both settings")
w("of the lever being varied, with the pair count reported. A feasibility")
w("share such as 0.685 is the fraction of the remaining lever combinations in")
w("the design that solve — not a real-world probability. The design is a")
w("complete factorial, so these shares are balanced and comparable to each")
w("other.")
w("")

w("## 1. Design and solve counts")
w("")
w(f"- Scenarios: **{len(df):,}**")
w(f"- Feasible: **{df.ok.sum():,}** ({df.ok.mean():.1%})")
w(f"- Infeasible: **{(~df.ok).sum():,}**  |  Errors: **0**")
w(f"- Feasible AND inside the tariff calibration band: **{len(cal):,}**")
w("- Complete factorial: "
  f"**{bool((df.groupby(COORDS, observed=True).size() == 1).all())}**")
w("")

w("## 2. Lever ranking by effect on feasibility")
w("")
w("*Swing* = P(feasible) at the lever's most permissive level minus its least.")
w("*Decisive* = share of otherwise-identical scenario groups whose feasibility")
w("changes when the lever moves.")
w("")
rows = []
for lev in LEVERS + ["avg_emi"]:
    g = df.groupby(lev, observed=True).ok.mean()
    keys = [c for c in COORDS if c != lev]
    grp = df.groupby(keys, observed=True).ok.agg(["min", "max"])
    rows.append({"lever": lev, "swing": g.max() - g.min(),
                 "decisive": (grp["min"] != grp["max"]).mean(),
                 "least permissive": f"{g.idxmin()} = {g.min():.3f}",
                 "most permissive": f"{g.idxmax()} = {g.max():.3f}"})
rank = pd.DataFrame(rows).sort_values("swing", ascending=False).set_index("lever")
rank["swing"] = rank.swing.map("{:.3f}".format)
rank["decisive"] = rank.decisive.map("{:.1%}".format)
table(rank, "lever")

w("## 3. Feasibility surface: scrap growth x H2 debut, within each target")
w("")
w("P(feasible). Rows = annual scrap-availability growth; columns = year green")
w("H2-DRI becomes available.")
w("")
for tgt in AX.AVG_EMI:
    w(f"### Emissions target {tgt} tCO2/t crude steel")
    w("")
    table(df[df.avg_emi == tgt].pivot_table(
        index="scrap_rate", columns="h2_start", values="ok", aggfunc="mean"),
        "scrap growth")

w("## 4. Corner comparison: is either dominant lever sufficient alone?")
w("")
lo_s, hi_s = min(AX.SCRAP_RATE), max(AX.SCRAP_RATE)
lo_h, hi_h = min(AX.H2_START), max(AX.H2_START)
rows = []
for tgt in AX.AVG_EMI:
    d = df[df.avg_emi == tgt]
    c = lambda s, h: d[(d.scrap_rate == s) & (d.h2_start == h)].ok.mean()
    rows.append({"target": tgt,
                 f"neither (scrap {lo_s}, H2 {hi_h})": c(lo_s, hi_h),
                 f"H2 only (scrap {lo_s}, H2 {lo_h})": c(lo_s, lo_h),
                 f"scrap only (scrap {hi_s}, H2 {hi_h})": c(hi_s, hi_h),
                 f"both (scrap {hi_s}, H2 {lo_h})": c(hi_s, lo_h)})
table(pd.DataFrame(rows).set_index("target"), "target")

w("## 5. Grid emission factor x H2 debut")
w("")
w("P(feasible). Grid EF in tCO2/kWh (0.00005 = 50 gCO2/kWh).")
w("")
table(df.pivot_table(index="grid_ef_target", columns="h2_start", values="ok",
                     aggfunc="mean"), "2050 grid EF")

w("## 6. Resource levers")
w("")
w("P(feasible) by coking-coal availability and gas allocation.")
w("")
table(df.pivot_table(index="ccoal", columns="ng", values="ok",
                     aggfunc="mean", observed=True), "coking coal")
w("Same, split by emissions target:")
w("")
table(df.pivot_table(index=["ccoal", "ng"], columns="avg_emi", values="ok",
                     aggfunc="mean", observed=True), "coal / gas")

w("## 7. Where infeasibility concentrates")
w("")
bad = df[~df.ok]
w(f"Of {len(bad):,} infeasible scenarios, the distribution across levels is:")
w("")
for lev in ("avg_emi", "h2_start", "scrap_rate"):
    share = (bad.groupby(lev, observed=True).size() / len(bad)).round(3)
    w(f"- **{lev}**: " + ", ".join(f"{k} = {v:.1%}" for k, v in share.items()))
w("")
w("Slices infeasible under *every* configuration of the other six levers:")
w("")
for tgt in AX.AVG_EMI:
    d = df[df.avg_emi == tgt]
    p = d.pivot_table(index="scrap_rate", columns="h2_start", values="ok",
                      aggfunc="mean")
    dead = [f"scrap {s} / H2 {h}" for s in p.index for h in p.columns
            if p.loc[s, h] == 0]
    w(f"- target {tgt}: {'; '.join(dead) if dead else 'none'}")
w("")

w("## 8. Cost of delaying the hydrogen debut")
w("")
w("LCOP penalty, $/t crude steel, against a 2030 debut. Calibrated scenarios")
w("only, emissions target 1.8, abundant coking coal, policy gas allocation.")
w("Blank = infeasible at that delay for every surviving pair.")
w("")
base = cal[(cal.ccoal == "abundant") & (cal.ng == "policy") & (cal.avg_emi == 1.8)]
delay = {}
for hi in (2035, 2040, 2045):
    t = paired(base, "h2_start", 2030, hi, by="scrap_rate")
    delay[f"to {hi}"] = t.delta.round(2)
    delay[f"n pairs ({hi})"] = t.n_pairs
table(pd.DataFrame(delay), "scrap growth", "{:.2f}")

w("## 9. Retirement policy (mandated phase-out of the 2025 fleet)")
w("")
d, n = paired(cal, "legacy", "run-life", "mandated-phaseout")
w(f"Overall: **{d:+.2f} $/t**, {n:,} pairs. Emissions identical — the")
w("cumulative cap binds either way — so this is avoided capital expenditure.")
w("")
w("By H2 debut year:")
w("")
t = paired(cal, "legacy", "run-life", "mandated-phaseout", by="h2_start")
table(t.round(2), "H2 debut", "{:.2f}")

w("## 10. Annual conventional build budget")
w("")
for lo, hi in (("tight", "mid"), ("tight", "loose"), ("mid", "loose")):
    d, n = paired(cal, "build_cap", lo, hi)
    w(f"- {lo} -> {hi}: **{d:+.2f} $/t** ({n:,} pairs)")
w("")
w("By H2 debut year (20 -> 40 Mt/yr):")
w("")
t = paired(cal, "build_cap", "tight", "loose", by="h2_start")
table(t.round(2), "H2 debut", "{:.2f}")

w("## 11. Electrolyser deployment rate")
w("")
for lo, hi in (("low", "medium"), ("medium", "high")):
    d, n = paired(cal, "ramp", lo, hi)
    w(f"- {lo} -> {hi}: **{d:+.2f} $/t** ({n:,} pairs)")
w("")
w("Effect on the 2050 hydrogen share and installed H2-DRI capacity:")
w("")
table(cal.groupby("ramp", observed=True)[["share_h2", "cap_h2dri_2050"]]
         .mean().round(4), "ramp")

w("## 12. Route shares in 2050, by scrap growth")
w("")
w("Mean shares of 2050 crude steel production, at a 2030 hydrogen debut,")
w("emissions target 1.8, abundant coal, policy gas.")
w("")
m = base[base.h2_start == 2030].groupby("scrap_rate", observed=True)[
    ["share_h2", "share_scrap", "share_bof", "share_cdri", "share_ngdri"]
].mean().round(4)
table(m, "scrap growth", "{:.4f}")

OUT.write_text("\n".join(buf) + "\n")
print(f"wrote {OUT} ({OUT.stat().st_size/1024:.0f} KB, {len(buf)} lines)")
